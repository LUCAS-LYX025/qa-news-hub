#!/bin/bash
# =============================================================================
#  自愈式端口感知启动器（供 launchd 与手动启动共用）
# -----------------------------------------------------------------------------
#  行为：
#   - 端口 5173 空闲 → 前台启动 vite；vite 退出后停顿 5s 再重试，实现「崩溃自愈」
#   - 端口被占用   → 每 30s 复查，绝不启动第二个 vite（避免双实例抢 data.json）
#  配合 launchd 的 KeepAlive，可在「进程被杀 / 电脑重启」后自动恢复服务。
# =============================================================================
cd "$(dirname "$0")" || exit 1

PORT=5173
while true; do
  if ! lsof -ti tcp:$PORT >/dev/null 2>&1; then
    echo "[dev-runner] 端口 $PORT 空闲，启动 vite..."
    npm run dev
    echo "[dev-runner] vite 已退出，${PORT} 将在 5s 后重试..."
    sleep 5
  else
    sleep 30
  fi
done
